import "dotenv/config";
import mongoose from "mongoose";

/**
 * One-time backfill for the move to derived "Actual Accomplishment" values.
 *
 * Before this change the text stored on a project was a snapshot that went stale
 * whenever a linked event was added/updated. Now the value is derived live from the
 * linked events, and the stored text is only used when `actual_accomplishment_override`
 * is true.
 *
 * For every project with stored text and no override flag yet:
 *   - text written by the old automation (the generated sentence or the legacy
 *     `[ref:...]` rollup lines) is cleared so the live value takes over;
 *   - anything else is treated as hand-written and flagged as a manual override.
 *
 * Usage: node scripts/backfill-accomplishment-override.mjs [--dry-run]
 */

const MONGODB_URI = process.env.MONGODB_URI;
if (!MONGODB_URI) {
  console.error("[backfill-accomplishment] MONGODB_URI is not defined in .env");
  process.exit(1);
}

const dryRun = process.argv.includes("--dry-run");

/* "2 events conducted — 'A', 'B' with 3 participants (2 Female, 1 Male)" */
const AUTO_SENTENCE =
  /^\s*\d+\s+events?\s+conducted\b.*\(\s*\d+\s+Female,\s*\d+\s+Male\s*\)\s*$/i;
/* Legacy rollup line: 'Conducted "X" on ... — 3 participants (1 Female, 1 Male, 1 Other) [ref:id]' */
const LEGACY_ROLLUP = /\[ref:[^\]]+\]/;

const looksAutoGenerated = (line) =>
  AUTO_SENTENCE.test(line) || LEGACY_ROLLUP.test(line);

async function run() {
  await mongoose.connect(MONGODB_URI);
  const col = mongoose.connection.collection("projects");

  const projects = await col
    .find({
      actual_accomplishment: { $exists: true, $ne: [] },
      actual_accomplishment_override: { $ne: true },
    })
    .toArray();

  console.log(
    `[backfill-accomplishment] ${projects.length} project(s) with stored text need review.`,
  );
  if (dryRun) {
    console.log("[backfill-accomplishment] dry run — no writes will be made.");
  }

  let cleared = 0;
  let keptAsOverride = 0;

  for (const project of projects) {
    const lines = (project.actual_accomplishment || []).map((line) =>
      String(line).trim(),
    );
    const meaningful = lines.filter(Boolean);

    if (meaningful.length === 0) continue;

    if (meaningful.every(looksAutoGenerated)) {
      cleared += 1;
      console.log(
        `[backfill-accomplishment] CLEAR ${project._id} — auto snapshot removed (live value takes over).`,
      );
      if (!dryRun) {
        await col.updateOne(
          { _id: project._id },
          { $set: { actual_accomplishment: [], actual_accomplishment_override: false } },
        );
      }
      continue;
    }

    keptAsOverride += 1;
    console.log(
      `[backfill-accomplishment] KEEP  ${project._id} — hand-written text flagged as override.`,
    );
    if (!dryRun) {
      await col.updateOne(
        { _id: project._id },
        { $set: { actual_accomplishment: meaningful, actual_accomplishment_override: true } },
      );
    }
  }

  console.log(
    `[backfill-accomplishment] done — cleared ${cleared}, kept as override ${keptAsOverride}${
      dryRun ? " (dry run)" : ""
    }.`,
  );

  await mongoose.disconnect();
}

run().catch(async (err) => {
  console.error("[backfill-accomplishment] failed:", err);
  await mongoose.disconnect().catch(() => {});
  process.exit(1);
});